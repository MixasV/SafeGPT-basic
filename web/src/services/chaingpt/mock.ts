/**
 * Picks a plausible mock audit for generated code, so the "audit what you just
 * generated" flow does not always return the same clean report.
 */
export function mockAudit(source: string): AuditResult {
  const risky = /mint\s*\(\s*\)|owner|onlyOwner|selfdestruct|delegatecall/.test(source);
  return risky ? MOCK_AUDIT_WITH_ISSUES : MOCK_AUDIT_CLEAN;
}