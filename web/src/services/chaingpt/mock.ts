/**
 * Simulated ChainGPT responses.
 *
 * Used when there is no API key, and as the fallback when a real call fails.
 * All of them are MARKDOWN, matching the real API's shape — a mock that returns
 * a different structure would let the UI look correct in demo mode and break the
 * moment a key is added.
 */

import type { AuditResult, ChatResult, GenerateResult } from "./types";

/** Wraps a body so the demo output looks like a real product response. */
function report(riskLevel: string, body: string): string {
  return `## Audit Report\n\n### Risk Level: ${riskLevel}\n\n${body}\n\n---\n_Generated by ChainGPT AI._`;
}

