/** Keyed by a crude topic guess so the demo answers stay on topic. */
export function mockChat(question: string): ChatResult {
  const text = question.toLowerCase();
  if (text.includes("rescue") || text.includes("recover")) return MOCK_CHAT_ANSWERS.rescue!;
  if (text.includes("allowance") || text.includes("approv")) return MOCK_CHAT_ANSWERS.allowance!;
  if (text.includes("alert")) return MOCK_CHAT_ANSWERS.alert!;
  return MOCK_CHAT_ANSWERS.default!;
}

