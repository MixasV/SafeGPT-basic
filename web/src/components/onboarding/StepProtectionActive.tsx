import type { Address } from "viem";

import { explorerAddressUrl } from "../../config/tokens";
import { useOnboardingStore, type SelectedAsset } from "../../state/onboarding";
import { resolveRpcUrl, resolveWssUrl } from "../../lib/integrations";
import { StatusBadge } from "../common/StatusBadge";
import { PrimaryButton, StepFrame } from "./StepFrame";

const ALCHEMY_KEY_STORAGE = "safegpt_alchemy_key";
const EXECUTOR_KEY_STORAGE = "EXECUTOR_KEY";
const TG_TOKEN_STORAGE = "safegpt_tg_bot_token";
const TG_CHAT_STORAGE = "safegpt_tg_chat_id";

interface StepProtectionActiveProps {
  onFinish: () => void;
  chainId: number;
  account: Address;
  vaultAddress: Address;
  safeAddress: string;
  assets: SelectedAsset[];
}

/**
 * Final step: shows the active protection status and downloads a ready-to-use
 * `config.yaml` for the bot.
 *
 * The generated config.yaml is COMPLETE — it includes the RPC endpoints (built
 * from the Alchemy key), the executor private key, the token list, the
 * whitelist, the rules and the alert credentials. The user downloads it, drops
 * it into `bot/config/config.yaml`, and runs `start-monitoring.bat` — no CLI
 * conversion step needed.
 *
 * Security note: the config.yaml contains secrets (executor key, Telegram
 * token). It is gitignored and stays on the user's machine. This is the OSS
 * self-hosted model: one file the user controls.
 */
export function StepProtectionActive({
  onFinish,
  chainId,
  account,
  vaultAddress,
  safeAddress,
  assets,
}: StepProtectionActiveProps) {
  const protectedAssets = assets.filter((asset) => asset.selected);

  const handleDownloadConfig = () => {
    const state = useOnboardingStore.getState();
    const alchemyKey = localStorage.getItem(ALCHEMY_KEY_STORAGE) ?? state.alchemyKey ?? "";
    const executorKey = localStorage.getItem(EXECUTOR_KEY_STORAGE) ?? "";
    const tgToken = localStorage.getItem(TG_TOKEN_STORAGE) ?? "";
    const tgChat = localStorage.getItem(TG_CHAT_STORAGE) ?? "";

    // Build RPC endpoints: Alchemy when a key is present, else public endpoints.
    const rpcHttp = resolveRpcUrl(chainId, alchemyKey) ?? "";
    const rpcWss = resolveWssUrl(chainId, alchemyKey) ?? "";

    // Verified assets are core (fee charged), unverified go to watch set.
    const coreTokens = protectedAssets.filter((a) => a.verified);
    const watchTokens = protectedAssets.filter((a) => !a.verified);

    // Build the config.yaml content manually for full control over formatting.
    // Using a template string rather than a YAML library to keep the output
    // clean, commented and deterministic.
    const lines: string[] = [
      "# SafeGPT bot configuration — generated by the onboarding wizard.",
      "# This file contains secrets (executor key, Telegram token). It is gitignored.",
      "# Place it at bot/config/config.yaml and run start-monitoring.bat.",
      "",
      `rpcWss: "${rpcWss}"`,
      `rpcHttp: "${rpcHttp}"`,
      `chainId: ${chainId}`,
      '# Flashbots relay (empty = public mempool). Set a relay URL to enable private bundles.',
      'flashbotsRelay: ""',
      "",
      "wallets:",
      "  - label: \"Main wallet\"",
      `    protectedWallet: "${account}"`,
      `    safeAddress: "${safeAddress}"`,
      `    vaultAddress: "${vaultAddress}"`,
      `    executorPrivateKey: "${executorKey}"`,
      "",
      "    # Verified assets — rescued WITH a fee, sent to safeAddress.",
      "    coreTokens:",
      ...(coreTokens.length > 0
        ? coreTokens.flatMap((a) => [
            `      - address: "${a.address}"`,
            `        symbol: "${a.symbol}"`,
            `        decimals: ${a.decimals}`,
            ...(a.threshold ? [`        rescueThreshold: "${a.threshold}"`] : []),
          ])
        : ["      []"]),
      "",
      "    # Unverified assets — rescued WITHOUT a fee, in a separate transaction.",
      "    watchTokens:",
      ...(watchTokens.length > 0
        ? watchTokens.flatMap((a) => [
            `      - address: "${a.address}"`,
            `        symbol: "${a.symbol}"`,
            `        decimals: ${a.decimals}`,
            ...(a.threshold ? [`        rescueThreshold: "${a.threshold}"`] : []),
          ])
        : ["      []"]),
      "",
      "    # Addresses the owner legitimately interacts with — no rescue triggered.",
      "    whitelist:",
      ...(state.whitelist.length > 0
        ? state.whitelist.map((addr) => `      - "${addr}"`)
        : ["      []"]),
      "",
      "    thresholds:",
      `      massTransferCount: ${state.rules.massTransfersMax}`,
      `      massTransferWindowMin: ${state.rules.massTransfersWindowMin}`,
      `      balanceDropPct: 10`,
      "",
      "alerts:",
      `  telegramBotToken: "${tgToken}"`,
      `  telegramChatId: "${tgChat}"`,
      '  webhookUrl: ""',
      "  minExecutorEth: 0.1",
      "",
    ];

    const yaml = lines.join("\n");
    const blob = new Blob([yaml], { type: "text/yaml" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "config.yaml";
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <StepFrame
      title="Protection active"
      subtitle="Your wallet is now monitored for suspicious outgoing transactions."
      footer={
        <div className="flex gap-2">
          <PrimaryButton onClick={onFinish}>Go to Dashboard</PrimaryButton>
          <button
            onClick={handleDownloadConfig}
            className="rounded-lg border border-border px-3 py-2 text-sm text-text-primary"
          >
            Download config.yaml
          </button>
        </div>
      }
    >
      <div className="flex items-center gap-3 rounded-lg border border-accent-green/40 bg-accent-green/10 p-4">
        <StatusBadge tone="active" label="ACTIVE" />
        <div>
          <p className="text-sm font-semibold text-accent-green">Monitoring started</p>
          <p className="text-sm text-text-secondary">
            If suspicious activity is detected, your funds are moved to the safe address before the attack
            transaction executes.
          </p>
        </div>
      </div>

      <dl className="grid gap-2 rounded-lg border border-border bg-bg-tertiary p-4 text-sm">
        <div className="flex justify-between gap-4">
          <dt className="text-text-secondary">Protected wallet</dt>
          <dd className="break-all font-mono text-text-primary">{account}</dd>
        </div>
        <div className="flex justify-between gap-4">
          <dt className="text-text-secondary">Safe address</dt>
          <dd className="break-all font-mono text-text-primary">{safeAddress}</dd>
        </div>
        <div className="flex justify-between gap-4">
          <dt className="text-text-secondary">Protection contract</dt>
          <dd className="break-all font-mono text-text-primary">
            <a
              className="text-accent"
              href={explorerAddressUrl(chainId, vaultAddress)}
              target="_blank"
              rel="noreferrer noopener"
            >
              {vaultAddress} ↗
            </a>
          </dd>
        </div>
        <div className="flex justify-between gap-4">
          <dt className="text-text-secondary">Protected assets</dt>
          <dd className="text-text-primary">{protectedAssets.length}</dd>
        </div>
      </dl>

      <div className="rounded-lg border border-border bg-bg-tertiary p-4 text-sm text-text-secondary">
        <p className="font-medium text-text-primary">Start monitoring</p>
        <p className="mt-1">
          Download the <code className="rounded bg-bg-secondary px-1">config.yaml</code> below, place it in{" "}
          <code className="rounded bg-bg-secondary px-1">safegpt-core/bot/config/config.yaml</code>, then run{" "}
          <code className="rounded bg-bg-secondary px-1">start-monitoring.bat</code> from the project root.
        </p>
        <p className="mt-2 text-xs">
          The config includes your executor key and alert credentials. Keep it private — it is gitignored.
        </p>
      </div>
    </StepFrame>
  );
}